// One opcode prefix occupies one guest word, held in uint32_t on the host.
template <Opcode operation> [[nodiscard]] consteval auto opcode() {
  return std::array{static_cast<std::uint32_t>(operation)};
}

// Concatenate encoded instructions at compile time, with no runtime assembler.
template <std::size_t... sizes>
  requires(sizeof...(sizes) != 0)
[[nodiscard]] consteval auto program(const std::array<std::uint32_t, sizes>... instructions) {
  std::array<std::uint32_t, (std::size_t{0} + ... + sizes)> result{};
  std::size_t position = 0;
  const auto append = [&](const auto words) {
    for (const auto word : words) { result[position++] = word; }
  };
  (append(instructions), ...);
  return result;
}

