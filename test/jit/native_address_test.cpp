int main() {
  try {
    dsp56300::test::admission();
    dsp56300::test::direct_matrix();
    for (const auto backend :
         {dsp56300::Backend::reference, dsp56300::Backend::cached, dsp56300::Backend::jit}) {
      dsp56300::test::core_checks({.backend = backend});
    }
    dsp56300::test::core_checks({.backend = dsp56300::Backend::jit, .optimize = false});
    std::cout << dsp56300::test::checks << " independent native address-update checks passed\n";
  } catch (const std::exception &error) {
    std::cerr << error.what() << '\n';
    return 1;
  }
}
