constexpr Word update_prefix = 0x204000, high_linear = 0xabffff;
constexpr Word io_address = 0xffff80, datum = 0xfedcba, mac_a = 0x2000d2, mac_b = 0x2000fa;
constexpr Word round_a = 0x200011, add_b = 0x200018, io_add = 0x56e010;
constexpr std::array numeric_modes{
    0U, mode_down, mode_up, mode_rm, mode_rm | mode_down, mode_rm | mode_up};
constexpr std::array<Word, 6> edge_words{0, 1, sign24 - 1, sign24, word_mask - 1, word_mask};

struct Shape {
  unsigned index = 0, mode = 0;
  Word numeric = 0;
};

Word opcode(const Shape shape) {
  return update_prefix | (shape.mode << 11) | (shape.index << 8);
}

Word next(const Registers &state, const Shape shape) {
  return address_model::updated({.modifier = state.m[shape.index],
                                 .cursor = state.r[shape.index],
                                 .offset = state.n[shape.index],
                                 .mode = shape.mode});
}

void admission() {
  for (unsigned index = 0; index < agu_registers; ++index) {
    for (unsigned mode = 0; mode < 4; ++mode) {
      for (const Word alu : {0U, round_a & status_byte, mac_a & status_byte}) {
        const detail::Instruction instruction{.opcode =
                                                  opcode({.index = index, .mode = mode}) | alu,
                                              .operation = detail::Operation::parallel};
        require(detail::pure_address_update(instruction) == (alu == 0),
                "Only declared pure update words enter the address-only native path");
        if (alu == 0) {
          const auto dataflow = detail::analyze_dataflow(instruction);
          require(dataflow.move_writes == 0 && dataflow.old_inputs == 0,
                  "AGU-only changes never invalidate live A/B/X/Y or capture old data banks");
        }
      }
    }
  }
  require(
      !detail::pure_address_update({.opcode = update_prefix, .operation = detail::Operation::nop}),
      "The move descriptor cannot override the decoded operation family");
}

struct Probe {
  unsigned calls = 0;
};

std::uint32_t forbidden_move(void *const owner, const detail::NativeOp * /*operation*/) noexcept {
  ++static_cast<Probe *>(owner)->calls;
  return 0;
}

struct Operand {
  Word cursor = 0, offset = 0, modifier = word_mask, flags = 0;
};

void direct_case(const native::Direct &code, const Shape shape, const Operand operand) {
  detail::Cpu cpu;
  cpu.reg = register_model::seed(shape.numeric);
  cpu.reg.sr = shape.numeric | operand.flags;
  cpu.reg.a <<= detail::padding_bits;
  cpu.reg.b <<= detail::padding_bits;
  cpu.reg.r[shape.index] = operand.cursor;
  cpu.reg.n[shape.index] = operand.offset;
  cpu.reg.m[shape.index] = operand.modifier;
  cpu.repeat_completed = cpu.interrupt_inhibited = true;
  auto expected = cpu.reg;
  const bool linear = (operand.modifier & address_model::linear) == address_model::linear;
  if (linear) {
    expected.r[shape.index] = next(expected, shape);
    ++expected.pc;
  }
  Probe probe;
  bool dirty = false;
  std::uint64_t transfers = 0;
  std::array<std::uint64_t, 4> latched{};
  detail::NativeContext context{.runtime = {.owner = &probe, .latched = &latched, .memory = {}},
                                .exit_requested = &dirty,
                                .native_moves = &transfers,
                                .budget = 1};
  const auto retired = code.enter(cpu, context);
  require(
      retired == (linear ? 1U : 0U) && probe.calls == (linear ? 0U : 1U) && cpu.reg == expected &&
          cpu.instructions == retired && cpu.cycles == retired && transfers == 0,
      "Identical generated bytes use no helper/RAM for linear updates and guard every changed M");
  if (linear) {
    require(
        !cpu.repeat_completed && !cpu.interrupt_inhibited,
        "Successful native address retirement clears transient instruction-boundary inhibition");
  }
}

void direct_operands(const native::Direct &code, const Shape shape, const Word flags) {
  for (const auto cursor : edge_words) {
    for (const auto offset : edge_words) {
      for (const auto modifier : {word_mask, high_linear}) {
        direct_case(code,
                    shape,
                    {.cursor = cursor, .offset = offset, .modifier = modifier, .flags = flags});
      }
    }
  }
}

void direct_shape(const Shape shape) {
  const std::array operations{detail::NativeOp{
      .instruction = {.opcode = opcode(shape), .operation = detail::Operation::parallel},
      .pc = start,
      .mode = shape.numeric}};
  detail::JitEmitter emitter({.moves = forbidden_move, .memory = {}}, true);
  const native::Direct code(emitter.generate(operations));
  require(!emitter.packed_retirement(),
          "Potential AGU helper fallback retains conservative counter publication");
  for (Word flags = 0; flags <= status_byte; ++flags) { direct_operands(code, shape, flags); }
  for (const Word modifier : {0U, 15U, 0x800fU, 0x8002U, 0xc001U}) {
    direct_case(code,
                shape,
                {.cursor = word_mask, .offset = 1, .modifier = modifier, .flags = status_byte});
  }
}

void direct_matrix() {
  for (unsigned index = 0; index < agu_registers; ++index) {
    for (unsigned mode = 0; mode < 4; ++mode) {
      for (const auto numeric : numeric_modes) {
        direct_shape({.index = index, .mode = mode, .numeric = numeric});
      }
    }
  }
}

struct Machine {
  explicit Machine(const Options options, Io *io = nullptr)
      : core({.program = p, .x = x, .y = y}, io, options) {}

  std::array<Word, memory_words> p{}, x{}, y{};
  Core core;
};

void core_reuse(const Options options, const Shape shape) {
  Machine machine(options);
  const std::array words{opcode(shape)};
  machine.core.load(Space::program, start, words);
  for (const Word modifier : {word_mask, high_linear, 15U, 0U, 0x800fU, word_mask}) {
    for (const Word cursor : {0U, 15U, 16U, io_address, word_mask}) {
      for (const Word offset : {0U, 1U, 2U, word_mask}) {
        auto state = register_model::seed(mode_rm);
        state.r[shape.index] = cursor;
        state.n[shape.index] = offset;
        state.m[shape.index] = modifier;
        auto expected = state;
        expected.r[shape.index] = next(state, shape);
        ++expected.pc;
        machine.core.set_registers(state);
        const auto before = machine.core.progress();
        const auto run = machine.core.run(1);
        require(run.dispatches == 1 && run.fault.kind == FaultKind::none &&
                    machine.core.registers() == expected &&
                    run.progress == Progress{.instructions = before.instructions + 1,
                                             .estimated_cycles = before.estimated_cycles + 1} &&
                    machine.x == std::array<Word, memory_words>{} && machine.y == machine.x,
                "Same-PC M/R/N changes preserve complete independent state and access no backing "
                "RAM/I/O");
      }
    }
  }
  if (options.backend == Backend::jit && options.optimize) {
    require(machine.core.jit_statistics().compiled_blocks == 1 &&
                machine.core.jit_statistics().native_move_instructions == 0,
            "Warm address updates reuse one guarded block without counting memory transfers");
  }
}

struct Step {
  Word word = 0;
  bool update = false;
  Shape shape{};
};

std::array<Step, 6> chain() {
  return {
      {{.word = mac_a},
       {.word = mac_b},
       {.word = opcode({.index = 2, .mode = 0}), .update = true, .shape = {.index = 2, .mode = 0}},
       {.word = round_a},
       {.word = opcode({.index = 3, .mode = 3}), .update = true, .shape = {.index = 3, .mode = 3}},
       {.word = mac_b}}};
}

void model_step(Registers &state, const Step step) {
  if (step.update) {
    state.r[step.shape.index] = next(state, step.shape);
  } else {
    sequence_model::alu(state, state, step.word);
  }
  ++state.pc;
}

std::vector<Word> words(const std::span<const Step> steps) {
  std::vector<Word> result;
  result.reserve(steps.size());
  for (const auto step : steps) { result.push_back(step.word); }
  return result;
}

Registers seed(const Word modifier) {
  auto state = register_model::seed(mode_up | flag_s | flag_l);
  state.r[0] = io_address;
  state.r[2] = word_mask;
  state.n[2] = word_mask;
  state.r[3] = 15;
  state.m[3] = modifier;
  return state;
}

void prefixes(const Options options, const Word modifier) {
  Machine machine(options);
  const auto program = chain();
  const auto code = words(program);
  machine.core.load(Space::program, start, code);
  const auto initial = seed(modifier);
  machine.core.set_registers(initial);
  require(machine.core.run(static_cast<Word>(program.size())).dispatches == program.size(),
          "Warm the complete arithmetic/address chain");
  for (Word budget = 0; budget <= program.size(); ++budget) {
    auto expected = initial;
    for (const auto step : std::span(program).first(budget)) { model_step(expected, step); }
    machine.core.set_registers(initial);
    const auto before = machine.core.progress();
    const auto run = machine.core.run(budget);
    require(
        run.dispatches == budget && run.fault.kind == FaultKind::none &&
            machine.core.registers() == expected &&
            run.progress == Progress{.instructions = before.instructions + budget,
                                     .estimated_cycles = before.estimated_cycles + budget} &&
            machine.core.interruptible(),
        "Every warm prefix retains both dirty accumulators across native and general AGU updates");
  }
  machine.core.set_registers(initial);
  auto expected = initial;
  std::size_t retired = 0;
  for (const Word budget : {2U, 1U, 2U, 1U}) {
    for (const auto step : std::span(program).subspan(retired, budget)) {
      model_step(expected, step);
    }
    require(machine.core.run(budget).dispatches == budget && machine.core.registers() == expected,
            "A partitioned chain resumes with canonical AGU and accumulator state");
    retired += budget;
  }
}

class Observer final : public Io {
public:
  Core *core = nullptr;
  Registers expected;
  unsigned calls = 0;
  bool observed = false, accept = true, invalidate = false;

  bool read(const Space space, const Word address, const Word pc, Word &value) noexcept override {
    ++calls;
    observed = core != nullptr && space == Space::x && address == io_address && pc == start + 6 &&
               core->registers() == expected &&
               core->progress() == Progress{.instructions = 6, .estimated_cycles = 6};
    if (observed && invalidate) { core->write(Space::program, start + 7, 0); }
    value = datum;
    return observed && accept;
  }

  bool write(Space /*space*/, Word /*address*/, Word /*pc*/, Word /*value*/) noexcept override {
    return false;
  }

  bool bit(Space /*space*/,
           Word /*address*/,
           Word /*pc*/,
           Word /*bit*/,
           BitAction /*action*/,
           bool & /*previous*/) noexcept override {
    return false;
  }
};

struct Callback {
  Options options;
  Word modifier = word_mask;
  bool accept = true, invalidate = false;
};

void callback(const Callback input) {
  Observer observer;
  observer.accept = input.accept;
  observer.invalidate = input.invalidate;
  Machine machine(input.options, &observer);
  observer.core = &machine.core;
  const auto initial = seed(input.modifier);
  const auto prefix = chain();
  auto program = words(prefix);
  program.insert(program.end(), {io_add, add_b});
  machine.core.load(Space::program, start, program);
  auto expected = initial;
  for (const auto step : prefix) { model_step(expected, step); }
  observer.expected = expected;
  ++observer.expected.pc;
  machine.core.set_registers(initial);
  const auto result = machine.core.run(static_cast<Word>(program.size()));
  require(observer.observed && observer.calls == 1,
          "Callbacks observe complete AGU, arithmetic, flags, PC and progress checkpoints");
  if (!input.accept) {
    require(result.dispatches == prefix.size() && result.progress.instructions == prefix.size() &&
                result.fault.kind == FaultKind::io_read && result.fault.pc == start + prefix.size(),
            "Rejected I/O retires only the independently checked arithmetic/address prefix");
    return;
  }
  const auto old = expected;
  register_model::write(expected, 14, datum);
  sequence_model::alu(expected, old, io_add);
  ++expected.pc;
  model_step(expected, {.word = input.invalidate ? 0U : add_b});
  require(
      result.dispatches == program.size() && result.fault.kind == FaultKind::none &&
          machine.core.registers() == expected,
      "Accepted and invalidating callbacks preserve old ALU operands after pure address updates");
}

void faults(const Options options) {
  for (const Word modifier : {0x8000U, 0x8002U, 0xc001U, 0xab8002U}) {
    Machine machine(options);
    const auto program = chain();
    const auto code = words(program);
    machine.core.load(Space::program, start, code);
    auto initial = seed(word_mask);
    machine.core.set_registers(initial);
    require(machine.core.run(static_cast<Word>(program.size())).dispatches == program.size(),
            "Warm linear state before a reserved-modifier guard miss");
    initial.m[3] = modifier;
    machine.core.set_registers(initial);
    auto expected = initial;
    for (const auto step : std::span(program).first(4)) { model_step(expected, step); }
    const auto before = machine.core.progress();
    const auto run = machine.core.run(static_cast<Word>(program.size()));
    const auto actual = machine.core.registers();
    require(run.dispatches == 4 &&
                run.progress == Progress{.instructions = before.instructions + 4,
                                         .estimated_cycles = before.estimated_cycles + 4} &&
                run.fault == Fault{.kind = FaultKind::unsupported_mode,
                                   .space = Space::program,
                                   .address = start + 4,
                                   .value = modifier & address_model::linear,
                                   .pc = start + 4} &&
                actual.a == expected.a && actual.b == expected.b && actual.r == expected.r &&
                actual.sr == expected.sr,
            "Failed dynamic guards preserve the general fault and every previously computed live "
            "value");
  }
  Machine machine(options);
  machine.core.write(Space::program, start, opcode({}));
  auto initial = seed(word_mask);
  initial.sr = mode_down | mode_up;
  machine.core.set_registers(initial);
  const auto run = machine.core.run(1);
  require(run.dispatches == 0 && run.fault.kind == FaultKind::unsupported_mode &&
              machine.core.registers().r == initial.r,
          "Unsupported numeric combinations cannot enter the native AGU path");
}

void loop_prefix(const Options options, const Word budget) {
  Machine machine(options);
  const auto full = chain();
  const std::array body{full[0], full[2], full[1], full[4]};
  constexpr Word count = 3;
  constexpr Word do_loop = 0x060380;
  constexpr Word loop_flag = Word{1} << 15;
  const auto ending = start + 1 + static_cast<Word>(body.size());
  std::vector<Word> program{do_loop, ending};
  const auto body_words = words(body);
  program.insert(program.end(), body_words.begin(), body_words.end());
  machine.core.load(Space::program, start, program);
  const auto initial = seed(word_mask);
  auto expected = initial;
  if (budget != 0) {
    expected.stack[3] = (std::uint64_t{initial.la} << word_bits) | initial.lc;
    expected.stack[4] = (std::uint64_t{start + 2} << word_bits) | initial.sr;
    expected.sp += 2;
    expected.sc += 2;
    expected.pc = start + 2;
    expected.la = ending;
    expected.lc = count;
    expected.sr |= loop_flag;
    for (Word retired = 1; retired < budget; ++retired) {
      const auto position = (retired - 1) % static_cast<Word>(body.size());
      model_step(expected, body[position]);
      if (position + 1 == body.size()) {
        if (expected.lc > 1) {
          --expected.lc;
          expected.pc = start + 2;
        } else {
          expected.la = initial.la;
          expected.lc = initial.lc;
          expected.sp = initial.sp;
          expected.sc = initial.sc;
          expected.sr &= ~loop_flag;
        }
      }
    }
  }
  machine.core.set_registers(initial);
  const auto run = machine.core.run(budget);
  require(run.dispatches == budget && run.fault.kind == FaultKind::none &&
              machine.core.registers() == expected &&
              run.progress == Progress{.instructions = budget,
                                       .estimated_cycles = budget + (budget == 0 ? 0U : 4U)} &&
              machine.core.interruptible(),
          "Every native loop prefix and final general cleanup preserves AGU, frames and exact "
          "retirement");
}

void core_checks(const Options options) {
  for (unsigned index = 0; index < agu_registers; ++index) {
    for (unsigned mode = 0; mode < 4; ++mode) {
      core_reuse(options, {.index = index, .mode = mode});
    }
  }
  for (const Word limit : {1U, 2U, 3U, 8U, 64U}) {
    auto bounded = options;
    bounded.instructions_per_block = limit;
    for (const Word modifier : {word_mask, high_linear, 15U, 0U, 0x800fU}) {
      prefixes(bounded, modifier);
      callback({.options = bounded, .modifier = modifier});
      callback({.options = bounded, .modifier = modifier, .accept = false});
      callback({.options = bounded, .modifier = modifier, .invalidate = true});
    }
  }
  faults(options);
  constexpr Word loop_budget = 13;
  for (Word budget = 0; budget <= loop_budget; ++budget) { loop_prefix(options, budget); }
}
